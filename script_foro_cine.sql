-- ------------------------------------------------------------
-- 2) TABLAS - ms-usuarios
-- ------------------------------------------------------------
CREATE TABLE ROL (
    ID_ROL   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE   VARCHAR2(30) NOT NULL UNIQUE
);

CREATE TABLE USUARIO (
    ID_USUARIO      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE          VARCHAR2(80)  NOT NULL,
    CORREO          VARCHAR2(120) NOT NULL UNIQUE,
    CONTRASENA      VARCHAR2(100) NOT NULL,
    FECHA_REGISTRO  TIMESTAMP(6),
    ID_ROL          NUMBER NOT NULL,
    CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ID_ROL) REFERENCES ROL (ID_ROL)
);

-- ------------------------------------------------------------
-- 3) TABLAS - ms-foro
-- ------------------------------------------------------------
CREATE TABLE CATEGORIA (
    ID_CATEGORIA  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE        VARCHAR2(60)  NOT NULL UNIQUE,
    DESCRIPCION   VARCHAR2(200)
);

CREATE TABLE TEMA (
    ID_TEMA       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITULO        VARCHAR2(150)  NOT NULL,
    CONTENIDO     VARCHAR2(2000) NOT NULL,
    FECHA         TIMESTAMP(6),
    ESTADO        VARCHAR2(20),
    ID_USUARIO    NUMBER NOT NULL,   -- referencia logica a USUARIO (otro microservicio)
    ID_CATEGORIA  NUMBER NOT NULL,
    CONSTRAINT FK_TEMA_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA (ID_CATEGORIA)
);

CREATE TABLE COMENTARIO (
    ID_COMENTARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONTENIDO     VARCHAR2(1000) NOT NULL,
    FECHA         TIMESTAMP(6),
    ESTADO        VARCHAR2(20),
    ID_USUARIO    NUMBER NOT NULL,   -- referencia logica a USUARIO (otro microservicio)
    ID_TEMA       NUMBER NOT NULL,
    CONSTRAINT FK_COMENTARIO_TEMA FOREIGN KEY (ID_TEMA) REFERENCES TEMA (ID_TEMA)
);

